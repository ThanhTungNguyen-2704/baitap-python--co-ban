# Nhập vào: tên, tuổi, ngành học
# In ra một "thẻ sinh viên" như sau:
#
# ╔══════════════════════╗
# ║    THẺ SINH VIÊN     ║
# ║  Tên  : Minh         ║
# ║  Tuổi : 20           ║
# ║  Ngành: CNTT         ║
# ╚══════════════════════╝
#
# Dùng f-string để ghép thông tin vào.

print( "╔══════════════════════╗")
print(f"║    THẺ SINH VIÊN     ║")
print(f"║  Tuổi : 20           ║")
print(f'║  Ngành: CNTT         ║')
print(f"╚══════════════════════╝")