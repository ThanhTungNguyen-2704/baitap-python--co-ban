# Khai báo các biến sau, sau đó in ra type() của từng biến:
# - Tên bạn (str)
# - Tuổi (int)
# - Điểm GPA (float)
# - Đang học đại học không? (bool)

# Gợi ý output mong muốn:
# ten = "Minh"  →  <class 'str'>
# tuoi = 20     →  <class 'int'>
# ...

name = str("Nguyen Thanh Tùng")
age = int(20) 
gpa = float(3.66)
isStudyUniversity = bool() ;
print(type(name))
print(type(age))
print(type(gpa))
print(type(isStudyUniversity))
